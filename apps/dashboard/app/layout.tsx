import "./globals.css";
import type { Metadata } from "next";
import { GeistSans } from "geist/font/sans";

import { AuthKitProvider, Impersonation } from '@workos-inc/authkit-nextjs/components';

export const metadata: Metadata = {
  title: "Create Turborepo",
  description: "Generated by create turbo",
};

import { AppSidebar } from "@components/app-sidebar"
import {
  SidebarInset,
  SidebarProvider,
  SidebarTrigger,
} from "@repo/ui/components/sidebar"

import { getCurrentSession } from "@/lib/workos/session";
import { getMyOrganizations } from "@/lib/workos/organizations";

export default async function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {

  const [{ user, organizationId }, organizations] =
    await Promise.all([
      getCurrentSession(),
      getMyOrganizations(),
    ]);

  const name =
    user.name ||
    [user.firstName, user.lastName].filter(Boolean).join(" ") ||
    user.email;


  return (
    <html lang="en">
      <body className={GeistSans.className}>
        <AuthKitProvider>
          <Impersonation />
          <SidebarProvider>
            <AppSidebar
              user={{
                name,
                email: user.email,
                avatar: user.profilePictureUrl,
              }}
              organizations={organizations}
              activeOrganizationId={organizationId ?? null}
            />
            <SidebarInset>
              <SidebarTrigger className="-ml-1" />
              {children}
            </SidebarInset>
          </SidebarProvider>
          
        </AuthKitProvider>
      </body>
    </html>
  );
}
